export function buildActions(): ActionItem[] {
  return ACTIONS.map(
    ([title, description, departmentId, priority, due, status, incidentId, created], i) => ({
      id: `ACT-${String(101 + i)}`,
      title,
      description,
      departmentId,
      priority,
      dueDate: demoDay(-due),
      status,
      incidentId,
      createdAt: demoDate(created, 12),
      completedAt: status === "completed" ? demoDate(Math.max(created - 2, 0), 17) : undefined,
      comments:
        i % 3 === 0
          ? [
              {
                id: `C-${i}-1`,
                author: "Collector's Office",
                text: "Please share a status update with photographs.",
                date: demoDate(Math.max(created - 1, 0), 15),
              },
            ]
          : [],
    }),
  );
}

