export function buildSyncLogs(): SyncLog[] {
  const logs: SyncLog[] = [];
  const sources = buildSources();
  sources.forEach((s, si) => {
    for (let k = 0; k < 5; k++) {
      const failed = (s.status === "failed" && k === 0) || (si + k) % 11 === 7;
      logs.push({
        id: `LOG-${s.id}-${k}`,
        sourceId: s.id,
        startedAt: demoDate(Math.floor(k / 2), 9 - k * 2, 0),
        durationSec: 4 + ((si * 7 + k * 3) % 40),
        status: s.status === "pending" ? "partial" : failed ? "failed" : "success",
        records: failed || s.status === "pending" ? 0 : 2 + ((si * 5 + k) % 18),
        message:
          s.status === "pending"
            ? "Adapter not configured — awaiting backend implementation"
            : failed
              ? s.type === "public_webpage"
                ? "HTTP 403 / content blocked by source"
                : "Connection timeout after 30s"
              : "Completed",
      });
    }
  });
  return logs;
}
